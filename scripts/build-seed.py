#!/usr/bin/env python3
"""Build deterministic Supabase seed SQL from the static site's embedded decks array."""
from __future__ import annotations

import argparse
import json
import re
import uuid
from pathlib import Path

NAMESPACE = uuid.UUID("0f8f29dd-85e0-4eb7-8c23-c7c9f8e22af7")
ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SOURCE = ROOT / "index.html"
DEFAULT_OUTPUT = ROOT / "supabase" / "seed.sql"


def sql(value: object) -> str:
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    return "'" + str(value).replace("'", "''") + "'"


def parse_decks(source: Path) -> list[dict]:
    text = source.read_text(encoding="utf-8")
    match = re.search(r"\bconst\s+decks\s*=", text)
    if not match:
        raise ValueError("could not find const decks = in source")
    decoder = json.JSONDecoder()
    start = match.end()
    while start < len(text) and text[start].isspace():
        start += 1
    decks, end = decoder.raw_decode(text[start:])
    if not isinstance(decks, list):
        raise ValueError("decks value is not an array")
    if len(decks) != 12:
        raise ValueError(f"expected 12 decks, found {len(decks)}")
    for deck in decks:
        cards = deck.get("cards")
        if not isinstance(cards, list) or len(cards) != 100:
            raise ValueError(f"deck {deck.get('id')} does not contain 100 cards")
        words = [card.get("word") for card in cards]
        if len(words) != len(set(words)):
            raise ValueError(f"duplicate word in deck {deck.get('id')}")
    return decks


def build(decks: list[dict]) -> str:
    lines = [
        "-- Generated by scripts/build-seed.py; deterministic UUIDs preserve local progress.",
        "begin;",
        "",
        "insert into public.phonetic_decks (id, name, native, flag, region, lang, position, published) values",
    ]
    deck_rows = []
    for pos, d in enumerate(decks):
        deck_rows.append("  (%s, %s, %s, %s, %s, %s, %d, true)" % (
            sql(d["id"]), sql(d["name"]), sql(d["native"]), sql(d["flag"]),
            sql(d["region"]), sql(d["lang"]), pos))
    lines.append(",\n".join(deck_rows) + "\non conflict (id) do nothing;")
    lines += ["", "insert into public.phonetic_cards (id, deck_id, word, roman, hint, meaning, cue, position, published, legacy_index, topic, difficulty) values"]
    card_rows = []
    for deck in decks:
        for index, card in enumerate(deck["cards"]):
            card_id = uuid.uuid5(NAMESPACE, f"{deck['id']}:{index}:{card['word']}")
            card_rows.append("  (%s, %s, %s, %s, %s, %s, %s, %d, true, %d, %s, %d)" % (
                sql(card_id), sql(deck["id"]), sql(card["word"]), sql(card.get("roman", "")),
                sql(card["hint"]), sql(card["meaning"]), sql(card.get("cue", "")), index, index,
                sql(card.get("topic", "general")), int(card.get("difficulty", 1))))
    lines.append(",\n".join(card_rows) + "\non conflict (id) do nothing;")
    lines += ["", "commit;", ""]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    decks = parse_decks(args.source)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(build(decks), encoding="utf-8")
    print(f"wrote {len(decks)} decks and {sum(len(d['cards']) for d in decks)} cards to {args.output}")


if __name__ == "__main__":
    main()
