#!/usr/bin/env python3
"""Build a compact JSON-driven seed SQL upload file from index.html."""
from __future__ import annotations
import argparse, json, re, uuid
from pathlib import Path

NAMESPACE = uuid.UUID("0f8f29dd-85e0-4eb7-8c23-c7c9f8e22af7")
ROOT = Path(__file__).resolve().parents[1]

def parse(source: Path) -> list[dict]:
    text = source.read_text(encoding="utf-8")
    match = re.search(r"\bconst\s+decks\s*=", text)
    if not match:
        raise ValueError("could not find const decks = in source")
    value, _ = json.JSONDecoder().raw_decode(text[match.end():].lstrip())
    if len(value) != 12 or any(len(d.get("cards", [])) != 100 for d in value):
        raise ValueError("expected exactly 12 decks with 100 cards each")
    return value

def sql(value: object) -> str:
    return "'" + json.dumps(value, ensure_ascii=False, separators=(",", ":")).replace("'", "''") + "'::jsonb"

def build(decks: list[dict]) -> str:
    deck_rows = [{k: d[k] for k in ("id", "name", "native", "flag", "region", "lang")} | {"position": i, "published": True} for i, d in enumerate(decks)]
    card_rows = []
    for d in decks:
        for i, c in enumerate(d["cards"]):
            card_rows.append({"id": str(uuid.uuid5(NAMESPACE, f'{d["id"]}:{i}:{c["word"]}')), "deck_id": d["id"], "word": c["word"], "roman": c.get("roman", ""), "hint": c["hint"], "meaning": c["meaning"], "cue": c.get("cue", ""), "position": i, "published": True, "legacy_index": i})
    return f'''-- Compact JSON seed generated by scripts/build-seed-json.py; safe to rerun.
begin;
with deck_rows as (
  select * from jsonb_to_recordset({sql(deck_rows)}) as x(id text, name text, native text, flag text, region text, lang text, position integer, published boolean)
)
insert into public.phonetic_decks(id,name,native,flag,region,lang,position,published)
select id,name,native,flag,region,lang,position,published from deck_rows on conflict (id) do nothing;
with card_rows as (
  select * from jsonb_to_recordset({sql(card_rows)}) as x(id uuid, deck_id text, word text, roman text, hint text, meaning text, cue text, position integer, published boolean, legacy_index integer)
)
insert into public.phonetic_cards(id,deck_id,word,roman,hint,meaning,cue,position,published,legacy_index)
select id,deck_id,word,roman,hint,meaning,cue,position,published,legacy_index from card_rows on conflict (id) do nothing;
commit;
'''

def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--source", type=Path, default=ROOT / "index.html")
    ap.add_argument("--output", type=Path, default=ROOT / "supabase" / "seed_compact.sql")
    args = ap.parse_args()
    args.output.write_text(build(parse(args.source)), encoding="utf-8")
    print(f"wrote compact JSON seed to {args.output}")

if __name__ == "__main__":
    main()
