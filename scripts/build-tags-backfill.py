#!/usr/bin/env python3
"""Build the one-time additive metadata backfill for the original 12 x 100 cards."""
from pathlib import Path
import json
import re

ROOT = Path(__file__).resolve().parents[1]
TOPICS = {'general','greetings','people','home','food','travel','time','numbers','expressions','nature','study','shopping','actions','descriptions'}

def quote(value):
    return "'" + str(value).replace("'", "''") + "'"

def build():
    source = (ROOT / 'index.html').read_text(encoding='utf-8')
    start = re.search(r'\bconst\s+decks\s*=', source).end()
    decks, _ = json.JSONDecoder().raw_decode(source[start:].lstrip())
    if len(decks) != 12 or any(len(d['cards']) != 100 for d in decks):
        raise ValueError('Expected the original 12 x 100 bundled cards')
    rows = []
    for deck in decks:
        for index, card in enumerate(deck['cards']):
            if card.get('topic') not in TOPICS or card.get('difficulty') not in (1,2,3):
                raise ValueError(f"Invalid metadata at {deck['id']}:{index}")
            rows.append(f"  ({quote(deck['id'])},{index},{quote(card['word'])},{quote(card['topic'])},{card['difficulty']})")
    return """-- Generated by scripts/build-tags-backfill.py from the original bundled card metadata.
-- Run only after 002_card_tags.sql. Never reload seed to upgrade an edited catalogue.
-- Only untouched default metadata is eligible; content, IDs, order and publication stay intact.
begin;
with metadata(deck_id, legacy_index, word, topic, difficulty) as (
  values
""" + ',\n'.join(rows) + """
)
update public.phonetic_cards as c
set topic=m.topic, difficulty=m.difficulty
from metadata as m
where c.deck_id=m.deck_id and c.legacy_index=m.legacy_index and c.word=m.word
  and c.topic='general' and c.difficulty=1;
notify pgrst, 'reload schema';
commit;
"""

if __name__ == '__main__':
    target = ROOT / 'supabase/migrations/003_backfill_card_tags.sql'
    target.write_text(build(), encoding='utf-8')
    print(f'Wrote one-time metadata backfill to {target}')
